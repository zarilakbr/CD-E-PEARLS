const LucideHelper = {
  get(iconName, size = 20, stroke = 1.8, extra = null) {
    if (LUCIDE_ICONS[iconName]) {
      return LUCIDE_ICONS[iconName](size, stroke, extra);
    }
    return '';
  },

  renderAll() {
    document.querySelectorAll('[data-lucide]').forEach(el => {
      const name = el.getAttribute('data-lucide');
      const size = parseInt(el.getAttribute('data-size') || '20', 10);
      const stroke = parseFloat(el.getAttribute('data-stroke') || '1.8');
      const fill = el.getAttribute('data-fill') || 'none';
      if (LUCIDE_ICONS[name]) {
        el.innerHTML = LUCIDE_ICONS[name](size, stroke, fill);
      }
    });
  }
};

if (typeof window !== 'undefined') {
  window.LucideHelper = LucideHelper;
  if (typeof document !== 'undefined') {
    document.addEventListener('DOMContentLoaded', () => {
      LucideHelper.renderAll();
    });
  }
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = LucideHelper;
}
